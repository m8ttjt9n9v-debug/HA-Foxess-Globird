"""Generate the immutable configuration FieldSpec catalogue."""

from __future__ import annotations

import argparse
import json
from pathlib import Path
from typing import Any

from scripts.config_field_amendments import reviewed_field_amendments

REPOSITORY_ROOT = Path(__file__).resolve().parents[1]
CONTRACT_PATH = (
    REPOSITORY_ROOT
    / "docs"
    / "maintainability"
    / "config-field-contract-v0.12.26.json"
)
CATALOGUE_PATH = (
    REPOSITORY_ROOT
    / "custom_components"
    / "home_energy_orchestrator"
    / "field_catalogue.py"
)
ADDITIONS_PATH = (
    REPOSITORY_ROOT / "docs" / "maintainability" / "config-field-additions-price-export-v1.json"
)
CAPACITY_ADDITIONS_PATH = (
    REPOSITORY_ROOT / "docs" / "maintainability" / "config-field-additions-ev-capacity-v1.json"
)
AMBER_ADDITIONS_PATH = (
    REPOSITORY_ROOT / "docs" / "maintainability" / "config-field-additions-amber-price-v1.json"
)
LOAD_ADDITIONS_PATH = (
    REPOSITORY_ROOT / "docs" / "maintainability" / "config-field-additions-load-power-v1.json"
)
SOLAR_SOAK_ADDITIONS_PATH = (
    REPOSITORY_ROOT / "docs" / "maintainability" / "config-field-additions-solar-soak-v1.json"
)
EV_EXPORT_BUFFER_ADDITIONS_PATH = (
    REPOSITORY_ROOT / "docs/maintainability/config-field-additions-ev-export-buffer-v1.json"
)
EV_LOCAL_CONNECTION_ADDITIONS_PATH = (
    REPOSITORY_ROOT / "docs/maintainability/config-field-additions-ev-local-connection-v1.json"
)
EV_IMPORT_ADDITIONS_PATH = (
    REPOSITORY_ROOT / "docs/maintainability/config-field-additions-ev-import-v1.json"
)
EV_SURPLUS_REARM_ADDITIONS_PATH = (
    REPOSITORY_ROOT / "docs/maintainability/config-field-additions-ev-surplus-rearm-v1.json"
)

_EV_PAGES = {"car", "charger", "ev_policies", "recovery"}


def _value_type(input_kind: str) -> str:
    return {
        "boolean": "bool",
        "entity": "entity_id",
        "number": "float",
        "select": "str",
        "text": "str",
        "time": "time",
    }[input_kind]


def _applicability(page: str) -> str:
    if page == "solar":
        return "solar"
    if page in _EV_PAGES:
        return "ev"
    return "always"


def _redaction(key: str, input_kind: str) -> str:
    if key == "name":
        return "redact"
    if input_kind == "entity":
        return "omit"
    return "retain"


def _field_line(field: dict[str, Any]) -> str:
    selector_config = field["input_config"]
    selector_config_json = (
        None
        if selector_config is None
        else json.dumps(selector_config, sort_keys=True, separators=(",", ":"))
    )
    return (
        "    FieldSpec("
        f"key={field['key']!r}, "
        f"value_type={_value_type(field['input_kind'])!r}, "
        f"default={field['default']!r}, "
        f"has_default={field['has_default']!r}, "
        f"selector_kind={field['input_kind']!r}, "
        f"selector_config_json={selector_config_json!r}, "
        f"page={field['page']!r}, "
        f"order={field['order']!r}, "
        f"required={field['required']!r}, "
        f"applicability={_applicability(field['page'])!r}, "
        f"redaction={_redaction(field['key'], field['input_kind'])!r}, "
        f"translation_key={field['key']!r}),"
    )


def rendered_catalogue() -> str:
    """Return deterministic Python source for every frozen wizard field."""
    contract = json.loads(CONTRACT_PATH.read_text(encoding="utf-8"))
    page_order = list(dict.fromkeys(field["page"] for field in contract["fields"]))
    fields = list(contract["fields"])
    known = {field["key"] for field in fields}
    for path in (
        ADDITIONS_PATH, CAPACITY_ADDITIONS_PATH, AMBER_ADDITIONS_PATH, LOAD_ADDITIONS_PATH,
        SOLAR_SOAK_ADDITIONS_PATH,
        EV_EXPORT_BUFFER_ADDITIONS_PATH,
        EV_LOCAL_CONNECTION_ADDITIONS_PATH,
        EV_IMPORT_ADDITIONS_PATH,
        EV_SURPLUS_REARM_ADDITIONS_PATH,
    ):
        additions = json.loads(path.read_text(encoding="utf-8"))
        if additions["field_count"] != len(additions["fields"]):
            raise ValueError("field catalogue additions have an invalid count")
        for field in additions["fields"]:
            if field["key"] in known:
                raise ValueError("field additions cannot replace reviewed keys")
            known.add(field["key"])
            if field["page"] not in page_order:
                page_order.append(field["page"])
            fields.append(field)
    contract["fields"] = sorted(
        fields, key=lambda field: (page_order.index(field["page"]), field["order"])
    )
    contract["fields"] = reviewed_field_amendments(contract["fields"])
    lines = [
        "# ruff: noqa: E501\n",
        '"""Generated immutable configuration field catalogue.\n',
        "\n",
        "Generated by ``scripts/field_catalogue.py`` from the reviewed v0.12.26\n",
        "configuration-field contract. Do not edit by hand.\n",
        '"""\n',
        "\n",
        "from __future__ import annotations\n",
        "\n",
        "from dataclasses import dataclass\n",
        "from types import MappingProxyType\n",
        "from typing import Literal\n",
        "\n",
        "\n",
        "@dataclass(frozen=True, slots=True)\n",
        "class FieldSpec:\n",
        '    """One stable persisted configuration-field definition."""\n',
        "\n",
        "    key: str\n",
        '    value_type: Literal["bool", "entity_id", "float", "str", "time"]\n',
        "    default: object\n",
        "    has_default: bool\n",
        "    selector_kind: str\n",
        "    selector_config_json: str | None\n",
        "    page: str\n",
        "    order: int\n",
        "    required: bool\n",
        '    applicability: Literal["always", "solar", "ev"]\n',
        '    redaction: Literal["retain", "redact", "omit"]\n',
        "    translation_key: str\n",
        "\n",
        "\n",
        'CATALOGUE_BASELINE = "0.12.26"\n',
        "FIELD_SPECS: tuple[FieldSpec, ...] = (\n",
    ]
    lines.extend(f"{_field_line(field)}\n" for field in contract["fields"])
    lines.extend(
        [
            ")\n",
            "FIELD_SPECS_BY_KEY = MappingProxyType(\n",
            "    {spec.key: spec for spec in FIELD_SPECS}\n",
            ")\n",
            "\n",
            "\n",
            "def _build_page_keys() -> MappingProxyType:\n",
            "    pages: dict[str, list[str]] = {}\n",
            "    for spec in FIELD_SPECS:\n",
            "        pages.setdefault(spec.page, []).append(spec.key)\n",
            "    return MappingProxyType(\n",
            "        {page: tuple(keys) for page, keys in pages.items()}\n",
            "    )\n",
            "\n",
            "\n",
            "FIELD_KEYS_BY_PAGE = _build_page_keys()\n",
        ]
    )
    return "".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--write", action="store_true")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    rendered = rendered_catalogue()
    if args.write:
        CATALOGUE_PATH.write_text(rendered, encoding="utf-8")
    if args.check and (
        not CATALOGUE_PATH.is_file()
        or CATALOGUE_PATH.read_text(encoding="utf-8") != rendered
    ):
        raise SystemExit("FieldSpec catalogue changed; review and regenerate")
    if not args.write and not args.check:
        print(rendered, end="")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
